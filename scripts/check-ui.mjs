import { chromium } from '@playwright/test';
const browser = await chromium.launch({args:['--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:900}});
await page.goto('http://127.0.0.1:5173/?test');
await page.waitForFunction(()=>window.aquaswarmSnapshot?.().time>2);
await page.screenshot({path:'evidence/ui-refined-desktop.png',fullPage:true});
await page.locator('#expand').click();
await page.waitForTimeout(300);
if(await page.locator('.controls').isVisible())throw new Error('Panel did not hide');
await page.screenshot({path:'evidence/ui-refined-expanded.png',fullPage:true});
await page.locator('#expand').click();
await page.setViewportSize({width:390,height:844});
await page.waitForTimeout(300);
await page.screenshot({path:'evidence/ui-refined-mobile.png',fullPage:true});
console.log({overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)});
await browser.close();
